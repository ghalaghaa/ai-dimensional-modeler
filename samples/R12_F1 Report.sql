    "C001_Suffix"."ID", 
    "C001_Suffix"."ACCOUNT_BASIC_NUMBER", 
    "C001_Suffix"."Created_BY_", 
    "C001_Suffix"."Risk_Score_Cateogry", 
    "C001_Suffix"."Risk_Score_Update_Date"
FROM
    (
    SELECT
        "Acc2"."ACCOUNT_NUMBER" AS "ACCOUNT_NUMBER", 
        "Acc2"."ACCOUNT_SUFFIX" AS "ACCOUNT_SUFFIX", 
        "Acc2"."ACCOUNT_BASIC_NUMBER" AS "ACCOUNT_BASIC_NUMBER", 
        "Acc2"."DATE_ACCOUNT_OPENED" AS "DATE_ACCOUNT_OPENED", 
        "Acc2"."DATE_ACCOUNT_CLOSED" AS "DATE_ACCOUNT_CLOSED", 
        "Acc2"."ID" AS "ID", 
        CASE 
            WHEN "Acc2"."created_by" = 'BAJDOM' THEN 'Mobile'
            WHEN "Acc2"."created_by" = 'BAJPORTAL' THEN 'Portal'
            ELSE "Acc2"."created_by"
        END AS "Created_BY_", 
        "Acc2"."Risk_Score_Cateogry" AS "Risk_Score_Cateogry", 
        "Acc2"."Risk_Score_Update_Date" AS "Risk_Score_Update_Date"
    FROM
        (
        SELECT ACCOUNT_NUMBER,ACCOUNT_SUFFIX,ACCOUNT_BASIC_NUMBER,DATE_ACCOUNT_OPENED,DATE_ACCOUNT_CLOSED,
SUBSTRING(C.CUSTOMER_REFERENCE,3,10) ID,a.created_by,' ' as Risk_Score_Cateogry,' ' as Risk_Score_Update_Date
FROM Equation_Presentation..D_ACCOUNT A, Equation_Presentation..D_CUSTOMER C,
Equation_Presentation..D_Customer_Additional_Detail2 d
WHERE A.ACCOUNT_BASIC_NUMBER=C.CUSTOMER_NUMBER
and c.Customer_Number = d.customer_Number
        ) "Acc2"("ACCOUNT_NUMBER", "ACCOUNT_SUFFIX", "ACCOUNT_BASIC_NUMBER", "DATE_ACCOUNT_OPENED", "DATE_ACCOUNT_CLOSED", "ID", "created_by", "Risk_Score_Cateogry", "Risk_Score_Update_Date") 
    WHERE 
        "Acc2"."ACCOUNT_SUFFIX" = '001' AND
        "Acc2"."DATE_ACCOUNT_OPENED" >= '2018-07-01'
    ) "C001_Suffix"

